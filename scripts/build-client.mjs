import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../client.js', import.meta.url);
const { outputFiles } = await build({
  absWorkingDir: root,
  entryPoints: ['client/entry.js'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  external: ['react', 'react-dom/client', '@deepseek-ai/dsh-client-ui-primitives'],
  banner: {
    js: "// Generated by npm run build:client. Edit client/ instead.\nwindow.__ModuleLoader__.load({ id: 'dsh-sihq', factory(require) {\nconst module = { exports: {} };",
  },
  footer: { js: 'return module.exports.default;\n} });' },
});
const output = outputFiles[0].text;
if (process.argv.includes('--check')) {
  const installed = await readFile(target, 'utf8');
  if (installed.replace(/\r\n/g, '\n') !== output) {
    throw new Error('client.js differs from client/ sources. Run npm run build:client.');
  }
} else {
  await writeFile(target, output);
}
